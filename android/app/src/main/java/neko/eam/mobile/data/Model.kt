/** Error raised for non-2xx responses; [target] is the field that failed validation, if any. */
class ApiException(
    val status: Int,
    val code: String,
    message: String,
    val target: String = "",
) : Exception(message) {
    val unauthorized get() = status == 401
}

// ---- helpers for the dynamic element JSON ----

/** Text of a primitive value, `null` for JSON null / missing. */
fun JsonElement?.text(): String? = when (this) {
    null, JsonNull -> null
    is JsonPrimitive -> contentOrNull
    else -> toString()
}

/** Values of a string collection. */
fun JsonElement?.strings(): List<String> = when (this) {
    null, JsonNull -> emptyList()
    is JsonPrimitive -> listOfNotNull(contentOrNull)
    else -> runCatching { jsonArray.mapNotNull { it.text() } }.getOrDefault(emptyList())
}

fun JsonObject.str(name: String): String = this[name].text().orEmpty()

/** Display name of an element. */
fun JsonObject.title(): String = str("name").ifEmpty { str("id") }

/** Human readable value of a field (booleans in [yes]/[no], collections comma separated). */
fun JsonObject.display(field: FieldDef, yes: String, no: String): String {
    val v = this[field.name]
    return when {
        field.isCollection -> v.strings().joinToString(", ")
        field.isBoolean -> when ((v as? JsonPrimitive)?.booleanOrNull) {
            true -> yes
            false -> no
            null -> ""
        }
        field.type == "Double" -> v.text()?.let { s -> s.toDoubleOrNull()?.let { formatNumber(it) } ?: s }.orEmpty()
        else -> v.text().orEmpty()
    }
}

internal fun formatNumber(d: Double): String =
    if (d == Math.floor(d) && !d.isInfinite() && kotlin.math.abs(d) < 1e15) d.toLong().toString() else d.toString()
