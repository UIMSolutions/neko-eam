/** `GET /auth/info` */
@Serializable
data class AuthInfo(
    val authMode: String = "none",
    val signedIn: Boolean = false,
    val multiTenant: Boolean = false,
) {
    val local get() = authMode == "local"
}

/** `POST /auth/login` request. */
@Serializable
data class LoginRequest(val userName: String, val password: String, val tenant: String = "")

/** `POST /auth/login` response. */
@Serializable
data class LoginResult(
    val userName: String = "",
    val displayName: String = "",
    val tenant: String = "",
    val mustChangePassword: Boolean = false,
)

/** One set of the meta model (`GET /api/v1/model`). */
@Serializable
data class EntitySetDef(
    val name: String,
    val typeName: String = "",
    val label: String = name,
    val icon: String = "",
    val fields: List<FieldDef> = emptyList(),
) {
    fun field(name: String) = fields.firstOrNull { it.name == name }

    /** Fields shown as secondary text in lists. */
    val listFields get() = fields.filter { it.listColumn && it.name != "name" }
}

/** A field of the meta model; `type` is the OData primitive type name. */
@Serializable
data class FieldDef(
    val name: String,
    val label: String = name,
    val type: String = "String",
    val group: String = "",
    val required: Boolean = false,
    val readOnly: Boolean = false,
    val listColumn: Boolean = false,
    val multiline: Boolean = false,
    val reference: String = "",
    val choices: List<String> = emptyList(),
    val defaultValue: String = "",
) {
    val isCollection get() = type == "StringCollection"
    val isReference get() = reference.isNotEmpty()
    val isNumber get() = type == "Int32" || type == "Double"
    val isBoolean get() = type == "Boolean"
    val isDate get() = type == "Date"

    /** Fields the edit form offers (`id` is generated by the server). */
    val editable get() = !readOnly && name != "id"
}

/** Permissions of the signed-in user on one set. */
@Serializable
data class SetAccess(
    val setName: String,
    val read: Boolean = true,
    val create: Boolean = false,
    val update: Boolean = false,
    val remove: Boolean = false,
)

@Serializable
data class AccessInfo(val sets: List<SetAccess> = emptyList(), val unrestricted: Boolean = false)

@Serializable
data class Tenant(val id: String = "", val name: String = "")

/** `GET /api/v1/me` */
@Serializable
data class Me(
    val name: String = "",
    val displayName: String = "",
    val initials: String = "",
    val email: String = "",
    val roles: List<String> = emptyList(),
    val canEdit: Boolean = false,
    val authMode: String = "none",
    val access: AccessInfo = AccessInfo(),
    val tenant: Tenant = Tenant(),
) {
    fun accessFor(set: String): SetAccess =
        access.sets.firstOrNull { it.setName == set }
            ?: if (access.unrestricted) SetAccess(set, true, true, true, true) else SetAccess(set, read = true)
}

